// Copies the third-party UI libraries the island uses into src/renderer/vendor/, so the app never loads code from a CDN.
//   node scripts/build-vendor.js        (after `npm install`; the output is committed)
// - Motion (motion.dev, MIT): spring animations
// - Lucide (lucide.dev, ISC): a fixed subset of icons, inlined as SVG strings
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const out = path.join(root, 'src', 'renderer', 'vendor');
const mod = (...p) => path.join(root, 'node_modules', ...p);
fs.mkdirSync(out, { recursive: true });

// Motion: the UMD build defines a global `Motion`.
const motionPkg = require(mod('motion', 'package.json'));
fs.copyFileSync(mod('motion', 'dist', 'motion.js'), path.join(out, 'motion.js'));
fs.copyFileSync(mod('motion', 'LICENSE.md'), path.join(out, 'motion.LICENSE.md'));

// Lucide: only the icons the UI uses. Name in the app -> Lucide file name.
const ICONS = {
  play: 'play',
  book: 'book-open',
  pause: 'pause',
  prev: 'skip-back',
  next: 'skip-forward',
  mic: 'mic',
  cam: 'video',
  timer: 'timer',
  stopwatch: 'timer-reset',
  hourglass: 'hourglass',
  alarm: 'alarm-clock',
  clock: 'clock-3',
  calendar: 'calendar-days',
  music: 'music',
  headphones: 'headphones',
  clip: 'clipboard',
  shelf: 'folder',
  file: 'file',
  download: 'download',
  battery: 'battery',
  bolt: 'zap',
  cpu: 'cpu',
  gear: 'settings',
  close: 'x',
  plus: 'plus',
  check: 'check',
  reset: 'rotate-ccw',
  flag: 'flag',
  stop: 'square',
  sun: 'sun',
  moonLine: 'moon',
  cloudSun: 'cloud-sun',
  bell: 'bell',
  star: 'star',
  pin: 'pin',
  volDown: 'volume-1',
  volUp: 'volume-2',
  mute: 'volume-x',
  globe: 'globe',
  search: 'search',
  todo: 'list-todo',
  grid: 'layout-grid',
  app: 'app-window',
};

const lucidePkg = require(mod('lucide-static', 'package.json'));
const entries = Object.entries(ICONS).map(([name, file]) => {
  const svg = fs
    .readFileSync(mod('lucide-static', 'icons', file + '.svg'), 'utf8')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s+/g, ' ')
    .replace(/ class="[^"]*"/, '')
    .replace(/ width="24"/, '')
    .replace(/ height="24"/, '')
    .replace(/> </g, '><')
    .trim();
  return `  ${name}: '${svg.replace(/'/g, "\\'")}',`;
});

fs.writeFileSync(
  path.join(out, 'lucide.js'),
  `// Generated by scripts/build-vendor.js from lucide-static ${lucidePkg.version} (ISC license, https://lucide.dev). Do not edit.\n` +
    `const LUCIDE = {\n${entries.join('\n')}\n};\n`
);
fs.copyFileSync(mod('lucide-static', 'LICENSE'), path.join(out, 'lucide.LICENSE'));

console.log(`vendor: motion ${motionPkg.version}, lucide-static ${lucidePkg.version} (${entries.length} icons)`);
