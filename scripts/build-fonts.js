// Copies the UI fonts into the project and writes their @font-face rules. No font is ever loaded from a CDN.
//   node scripts/build-fonts.js        (after `npm install`; the output is committed)
//
// Each pairing is one composite family: Arabic text takes the Arabic font, everything else (Latin, digits,
// punctuation) takes the Latin font, chosen per character by `unicode-range`, so an English song title inside
// the Arabic interface is set in the Latin font automatically.
//
// The files are the official per-script subsets published by Google Fonts (packaged by Fontsource), copied
// unmodified. IBM Plex has a Reserved Font Name ("Plex"): under the OFL a re-subset (modified) copy would
// have to be renamed, so we do not modify the files; the Arabic and Latin subsets are already small.
//
// Only the default pairing ships (assets/fonts/<id>/). The pairings shown for comparison go to dev/fonts/<id>/,
// which the Windows package excludes. Licenses (OFL 1.1) are copied next to the files.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const fontsource = (pkg, ...p) => path.join(root, 'node_modules', '@fontsource', pkg, ...p);

const SHIPPED = 'plex';
const WEIGHTS = [400, 500, 600, 700];
const PAIRINGS = {
  plex: { family: 'Islandly Plex', ar: 'ibm-plex-sans-arabic', lat: 'ibm-plex-sans' },
  manrope: { family: 'Islandly Manrope', ar: 'readex-pro', lat: 'manrope' },
  jakarta: { family: 'Islandly Jakarta', ar: 'alexandria', lat: 'plus-jakarta-sans' },
};
// Arabic glyphs sit a little smaller than Latin ones at the same font-size in these designs; scale them so a
// mixed line looks even. Tuned by eye on the comparison sheet (dev/fonts/compare.mjs).
const ARABIC_SIZE_ADJUST = { plex: '106%', manrope: '100%', jakarta: '100%' };

/** The unicode-range Fontsource publishes for one subset, read from its CSS so it stays exact. */
function rangeOf(pkg, subset) {
  const css = fs.readFileSync(fontsource(pkg, '400.css'), 'utf8');
  const m = new RegExp(`-${subset}-400-normal \\*/\\s*@font-face\\s*{[^}]*unicode-range:\\s*([^;]+);`).exec(css);
  if (!m) throw new Error(`no unicode-range for ${pkg} ${subset}`);
  return m[1].trim();
}

const report = [];
for (const [id, p] of Object.entries(PAIRINGS)) {
  const dir = id === SHIPPED ? path.join(root, 'assets', 'fonts', id) : path.join(root, 'dev', 'fonts', id);
  fs.rmSync(dir, { recursive: true, force: true });
  fs.mkdirSync(dir, { recursive: true });
  const faces = [];
  let bytes = 0;
  // Latin first, Arabic second: for the few shared code points (ZWNJ/ZWJ, hyphens) the later face wins,
  // so Arabic shaping keeps its own joiners.
  for (const [script, pkg, subset] of [
    ['lat', p.lat, 'latin'],
    ['ar', p.ar, 'arabic'],
  ]) {
    const range = rangeOf(pkg, subset);
    for (const w of WEIGHTS) {
      const src = fontsource(pkg, 'files', `${pkg}-${subset}-${w}-normal.woff2`);
      const file = `${script}-${w}.woff2`;
      fs.copyFileSync(src, path.join(dir, file));
      bytes += fs.statSync(src).size;
      faces.push(
        `@font-face {\n  font-family: '${p.family}';\n  font-style: normal;\n  font-weight: ${w};\n  font-display: swap;\n` +
          `  src: url('./${file}') format('woff2');\n` +
          (script === 'ar' && ARABIC_SIZE_ADJUST[id] !== '100%' ? `  size-adjust: ${ARABIC_SIZE_ADJUST[id]};\n` : '') +
          `  unicode-range: ${range};\n}`
      );
    }
    // the license exactly as published with the font in google/fonts (Fontsource's copy omits the RFN line)
    fs.copyFileSync(path.join(__dirname, 'licenses', `${pkg}.OFL.txt`), path.join(dir, `OFL-${pkg}.txt`));
  }
  const version = require(fontsource(p.ar, 'package.json')).version;
  fs.writeFileSync(
    path.join(dir, 'fonts.css'),
    `/* Generated by scripts/build-fonts.js. ${p.family}: ${p.ar} (Arabic) + ${p.lat} (Latin), @fontsource ${version}, SIL OFL 1.1. */\n` +
      faces.join('\n') +
      '\n'
  );
  report.push(`${id.padEnd(8)} ${(bytes / 1024).toFixed(0).padStart(4)} KB  ${path.relative(root, dir)}`);
}
console.log(report.join('\n'));
