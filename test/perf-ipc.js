const assert = require('node:assert/strict');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path');
const { app, BrowserWindow } = require('electron');
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'islandly-perf-ipc-'));
app.setPath('userData', temp);
fs.writeFileSync(path.join(temp, 'settings.json'), JSON.stringify({ weather: false, updates: false, clipboard: false, timeTracking: false, prayerAlerts: false }));
process.env.ISLANDLY_TEST = '1';
require('../src/main/main');
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
app.whenReady().then(async () => {
  await wait(1000);
  assert(global.__islandly, 'startup complete');
  const before = new Set(BrowserWindow.getAllWindows());
  global.__islandly.openSettings();
  const settings = BrowserWindow.getAllWindows().find(win => !before.has(win));
  assert(settings);
  if (settings.webContents.isLoading()) await new Promise(resolve => settings.webContents.once('did-finish-load', resolve));
  const metrics = await settings.webContents.executeJavaScript('settingsAPI.perf()');
  assert(metrics.totalMB > 0 && Array.isArray(metrics.processes));
  await settings.webContents.executeJavaScript("window.__samples=[]; window.__eco=[]; settingsAPI.on('perf:update', v => __samples.push(v)); settingsAPI.on('eco:changed', v => __eco.push(v)); settingsAPI.send('perf:watch', true);");
  await wait(6000);
  assert.equal(await settings.webContents.executeJavaScript('__samples.length'), 1);
  await settings.webContents.executeJavaScript('settingsAPI.set({ecoMode:true})');
  assert.equal(await settings.webContents.executeJavaScript('__eco.at(-1).eco'), true);
  settings.hide(); await wait(6000);
  assert.equal(await settings.webContents.executeJavaScript('__samples.length'), 1, 'hidden settings must stop updates');
  const foreign = new BrowserWindow({ show: false, webPreferences: { preload: path.join(__dirname, '../src/main/settings-preload.js'), contextIsolation: true, nodeIntegration: false, sandbox: true } });
  await foreign.loadURL('about:blank');
  const result = await foreign.webContents.executeJavaScript("settingsAPI.perf().then(() => 'unexpected', e => String(e))");
  assert.match(result, /Unauthorized/);
  foreign.destroy(); settings.destroy();
  console.log('real Electron perf IPC: scoped get/watch, 5s update, Eco change, hide cleanup and foreign-sender rejection passed');
  app.exit(0);
}).catch(err => { console.error(err); app.exit(1); });
